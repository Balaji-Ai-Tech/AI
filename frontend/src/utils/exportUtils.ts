export function downloadFile(filename: string, content: string | Blob, mimeType: string) {
  const blob = content instanceof Blob ? content : new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export function formatAsMarkdown(output: GeneratedOutputItem, docTitle: string): string {
  return `# ${docTitle} — ${output.title}
*Deliverable: ${output.type}*
*Generated by TransformHub AI*
*Status: ${output.approved ? 'Approved' : 'Draft - pending review'}*

---

## Key Facts & Core Findings
${output.keyFacts.map((fact) => `- ${fact}`).join('\n')}

## Operational & Strategic Impact
${output.impact}

## Strategic Directives & Recommendations
${output.recommendations.map((rec, i) => `${i + 1}. ${rec}`).join('\n')}

---

## Backend-Provided Source Excerpts
${output.evidence
  .map(
    (ev) =>
      `> "${ev.quote}"\n> — **${ev.page > 0 ? `Page ${ev.page}, ` : ''}${ev.section}**`
  )
  .join('\n\n')}
`;
}

export function formatAsJSON(output: GeneratedOutputItem, docTitle: string): string {
  return JSON.stringify(
    {
      documentTitle: docTitle,
      deliverableType: output.type,
      title: output.title,
      approved: output.approved,
      generatedTimestamp: new Date().toISOString(),
      keyFacts: output.keyFacts,
      operationalImpact: output.impact,
      recommendations: output.recommendations,
      sourceEvidence: output.evidence,
    },
    null,
    2
  );
}

