/**
 * Downloads a single output item as a formatted PDF.
 */
export function downloadSingleOutputPDF(output: GeneratedOutputItem, docTitle: string) {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'pt',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 40;
  const contentWidth = pageWidth - margin * 2;
  let y = margin;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.setTextColor(99, 102, 241);
  doc.text('TRANSFORMHUB AI • DELIVERABLE DISPATCH REPORT', margin, y);
  y += 14;
  doc.setDrawColor(226, 232, 240);
  doc.line(margin, y, pageWidth - margin, y);
  y += 20;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(15, 23, 42);
  const titleLines = doc.splitTextToSize(`${docTitle}: ${output.title}`, contentWidth);
  doc.text(titleLines, margin, y);
  y += titleLines.length * 20 + 10;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.setTextColor(71, 85, 105);
  doc.text('Key Findings & Core Insights:', margin, y);
  y += 16;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(30, 41, 59);
  output.keyFacts.forEach((f) => {
    const lines = doc.splitTextToSize(`• ${f}`, contentWidth);
    doc.text(lines, margin, y);
    y += lines.length * 12 + 4;
  });

  y += 10;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.setTextColor(71, 85, 105);
  doc.text('Operational Impact:', margin, y);
  y += 14;

  doc.setFont('helvetica', 'normal');
  const impactLines = doc.splitTextToSize(output.impact, contentWidth);
  doc.text(impactLines, margin, y);
  y += impactLines.length * 12 + 10;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.setTextColor(71, 85, 105);
  doc.text('Recommendations & Directives:', margin, y);
  y += 14;

  doc.setFont('helvetica', 'normal');
  output.recommendations.forEach((r, idx) => {
    const lines = doc.splitTextToSize(`${idx + 1}. ${r}`, contentWidth);
    doc.text(lines, margin, y);
    y += lines.length * 12 + 4;
  });

  const cleanName = `${docTitle}_${output.type}`.replace(/[^\w\s-]/g, '').trim().replace(/\s+/g, '_');
  doc.save(`${cleanName}_Report.pdf`);
}

/**
 * Downloads a completed transformation record as a formatted, multi-page PDF document
 * using jsPDF with corporate headers, metadata grids, key facts, impact, and evidence citations.
 */
export function downloadRecordAsPDF(record: CompletedTransformationRecord) {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'pt',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 40;
  const contentWidth = pageWidth - margin * 2;
  let y = margin;

  const checkPageBreak = (neededHeight: number) => {
    if (y + neededHeight > pageHeight - margin) {
      doc.addPage();
      y = margin;
      drawHeaderWatermark();
    }
  };

  const drawHeaderWatermark = () => {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8);
    doc.setTextColor(99, 102, 241);
    doc.text('TRANSFORMHUB AI • ENTERPRISE AUDIT & TRANSFORMATION REPORT', margin, y);
    y += 14;
    doc.setDrawColor(226, 232, 240);
    doc.setLineWidth(0.5);
    doc.line(margin, y, pageWidth - margin, y);
    y += 18;
  };

  drawHeaderWatermark();

  // Document Title
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(20);
  doc.setTextColor(15, 23, 42);
  const titleLines = doc.splitTextToSize(record.title, contentWidth);
  doc.text(titleLines, margin, y);
  y += titleLines.length * 24 + 4;

  // Metadata Box
  doc.setFillColor(248, 250, 252);
  doc.setDrawColor(226, 232, 240);
  doc.roundedRect(margin, y, contentWidth, 54, 4, 4, 'FD');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139);
  doc.text('STATUS', margin + 12, y + 16);
  doc.text('SOURCE FILE', margin + 120, y + 16);
  doc.text('AUDIENCE / TONE', margin + 290, y + 16);
  doc.text('EXECUTION DATE', margin + 420, y + 16);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(16, 185, 129);
  doc.text(`[✓] ${record.status}`, margin + 12, y + 36);

  doc.setTextColor(30, 41, 59);
  const sourceNameShort = record.sourceName.length > 25 ? record.sourceName.slice(0, 24) + '...' : record.sourceName;
  doc.text(sourceNameShort, margin + 120, y + 36);
  doc.text(`${record.configuration.audience} • ${record.configuration.tone}`, margin + 290, y + 36);
  doc.text(record.completedAt, margin + 420, y + 36);

  y += 68;

  // Executive Synopsis
  checkPageBreak(80);
  doc.setFillColor(238, 242, 255);
  doc.setDrawColor(99, 102, 241);
  doc.rect(margin, y, 4, 40, 'F');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.setTextColor(67, 56, 202);
  doc.text('EXECUTIVE SYNOPSIS', margin + 12, y + 12);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(30, 41, 59);
  const summaryLines = doc.splitTextToSize(record.summary || 'No summary was provided.', contentWidth - 20);
  doc.text(summaryLines, margin + 12, y + 26);
  y += Math.max(48, summaryLines.length * 12 + 20);

  // Deliverables Header
  checkPageBreak(40);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.setTextColor(15, 23, 42);
  doc.text(`Generated Outputs (${record.outputs.length})`, margin, y);
  y += 20;

  // Render each deliverable
  record.outputs.forEach((output, index) => {
    checkPageBreak(120);

    doc.setFillColor(241, 245, 249);
    doc.roundedRect(margin, y, contentWidth, 26, 3, 3, 'F');
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.setTextColor(30, 41, 59);
    doc.text(`${index + 1}. ${output.type}: ${output.title}`, margin + 10, y + 17);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(99, 102, 241);
    doc.text(output.approved ? 'APPROVED' : 'DRAFT - REVIEW', pageWidth - margin - 120, y + 17);
    y += 34;

    // Key Facts
    if (output.keyFacts && output.keyFacts.length > 0) {
      checkPageBreak(40);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(9);
      doc.setTextColor(71, 85, 105);
      doc.text('Key Findings & Core Insights:', margin, y);
      y += 14;

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(9);
      doc.setTextColor(30, 41, 59);
      output.keyFacts.forEach((fact) => {
        checkPageBreak(24);
        const bulletText = `•  ${fact}`;
        const factLines = doc.splitTextToSize(bulletText, contentWidth - 16);
        doc.text(factLines, margin + 8, y);
        y += factLines.length * 12 + 3;
      });
      y += 6;
    }

    // Operational Impact
    if (output.impact) {
      checkPageBreak(50);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(9);
      doc.setTextColor(71, 85, 105);
      doc.text('Operational Impact:', margin, y);
      y += 14;

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(9);
      doc.setTextColor(30, 41, 59);
      const impactLines = doc.splitTextToSize(output.impact, contentWidth - 8);
      doc.text(impactLines, margin + 8, y);
      y += impactLines.length * 12 + 8;
    }

    // Strategic Directives
    if (output.recommendations && output.recommendations.length > 0) {
      checkPageBreak(40);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(9);
      doc.setTextColor(71, 85, 105);
      doc.text('Strategic Directives & Action Items:', margin, y);
      y += 14;

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(9);
      doc.setTextColor(30, 41, 59);
      output.recommendations.forEach((rec, recIdx) => {
        checkPageBreak(24);
        const recText = `${recIdx + 1}.  ${rec}`;
        const recLines = doc.splitTextToSize(recText, contentWidth - 16);
        doc.text(recLines, margin + 8, y);
        y += recLines.length * 12 + 3;
      });
      y += 6;
    }

    // Evidence Citations
    if (output.evidence && output.evidence.length > 0) {
      checkPageBreak(50);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(9);
      doc.setTextColor(5, 150, 105);
      doc.text(`Source Excerpts (${output.evidence.length} backend-provided):`, margin, y);
      y += 14;

      output.evidence.forEach((ev) => {
        checkPageBreak(36);
        doc.setFillColor(240, 253, 244);
        doc.rect(margin + 8, y - 2, 3, 24, 'F');

        doc.setFont('helvetica', 'bold');
        doc.setFontSize(8);
        doc.setTextColor(4, 120, 87);
        const location = ev.page > 0 ? `Page ${ev.page} [${ev.section}]` : ev.section;
        const confidence = ev.confidenceScore > 0 ? `Confidence: ${Math.round(ev.confidenceScore * 100)}%` : 'Confidence not provided';
        doc.text(`${location} • ${confidence}`, margin + 16, y + 8);

        doc.setFont('helvetica', 'italic');
        doc.setFontSize(8);
        doc.setTextColor(30, 41, 59);
        const quoteLines = doc.splitTextToSize(`"${ev.quote}"`, contentWidth - 32);
        doc.text(quoteLines, margin + 16, y + 20);
        y += quoteLines.length * 10 + 16;
      });
    }

    y += 12;
    doc.setDrawColor(226, 232, 240);
    doc.setLineWidth(0.5);
    doc.line(margin, y, pageWidth - margin, y);
    y += 16;
  });

  // Footer on all pages
  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text(
      `TransformHub AI • Content Transformation Report • Page ${i} of ${totalPages}`,
      pageWidth / 2,
      pageHeight - 20,
      { align: 'center' }
    );
  }

  const cleanTitle = record.title.replace(/[^\w\s-]/g, '').trim().replace(/\s+/g, '_');
  doc.save(`${cleanTitle || 'Transformation'}_Report.pdf`);
}

export function downloadRecordAsJSON(record: CompletedTransformationRecord) {
  const jsonContent = JSON.stringify(record, null, 2);
  const cleanTitle = record.title.replace(/[^\w\s-]/g, '').trim().replace(/\s+/g, '_');
  downloadFile(`${cleanTitle || 'Transformation'}_Structured_Export.json`, jsonContent, 'application/json;charset=utf-8');
}

export function downloadAllRecordsAsJSON(records: CompletedTransformationRecord[]) {
  const payload = {
    exportDate: new Date().toISOString(),
    totalRecords: records.length,
    environment: 'TransformHub Enterprise Pipeline',
    schemaVersion: '2.0.0',
    records,
  };
  const filename = `TransformHub_History_Audit_${new Date().toISOString().slice(0, 10)}.json`;
  downloadFile(filename, JSON.stringify(payload, null, 2), 'application/json;charset=utf-8');
}
